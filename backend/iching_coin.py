def calc(tosses):
    """从 6 次掷爻结果计算本卦、变爻、变卦

    tosses: [{coins: [0|1, 0|1, 0|1]} × 6]，3 正面=老阳(动)，0 正面=老阴(动)
    """
    lines, changes = [], []
    for t in tosses:
        s = sum(t["coins"])
        idx_line = len(lines)          # 当前爻的索引
        if s == 3:      # 老阳 — 动爻
            lines.append(1); changes.append(idx_line)
        elif s == 0:    # 老阴 — 动爻
            lines.append(0); changes.append(idx_line)
        elif s == 2:    # 少阳
            lines.append(1)
        else:           # 少阴
            lines.append(0)

    lo, up = TRIGRAM.get(tuple(lines[0:3]), "乾"), TRIGRAM.get(tuple(lines[3:6]), "乾")
    idx = GUAMAP.get((up, lo), 1)          # (上卦, 下卦) → 文王卦序
    h1 = HEX.get(idx, HEX[1])

    # 变卦：动爻翻转
    c2 = lines.copy()
    for i in changes:
        c2[i] = 1 - c2[i]
    lo2, up2 = TRIGRAM.get(tuple(c2[0:3]), "乾"), TRIGRAM.get(tuple(c2[3:6]), "乾")
    idx2 = GUAMAP.get((up2, lo2), idx)
    h2 = HEX.get(idx2) if idx2 != idx else None

    return {
        "name": f"{h1[1]}{h1[0]}",
        "num": idx,
        "meaning": h1[2],
        "lines": lines,             # 本卦六爻阴阳（从下往上，1=阳 0=阴）
        "changed_lines": c2,        # 变卦六爻阴阳（从下往上）
        "changing": [i + 1 for i in changes],
        "changed": f"{h2[1]}{h2[0]}" if h2 and changes else None,
    }


def throw_coins():
    """模拟一次掷三枚硬币：1=正面，0=反面"""
    return [random.randint(0, 1) for _ in range(3)]


def random_hexagram():
    """随机起一卦（方便测试）"""
    return calc([{"coins": throw_coins()} for _ in range(6)])


def build_prompt(result, question="", context=""):
    """构建解卦 prompt（纯文本，不含 markdown）"""
    ch = f"变爻：第{','.join(str(i) for i in result['changing'])}爻" if result["changing"] else "静卦无变爻"
    ch2 = f"变卦：{result['changed']}" if result.get("changed") else ""
    q = f"\n求问者想问：{question}" if question else ""
    ctx = f"\n背景：{context}" if context else ""
    return f"""你是易经老人，精通六十四卦。求问者掷六爻得【{result['name']}】卦。
{result['meaning']}
{ch}
{ch2}{q}{ctx}
请依此真实卦象解答求问者的问题，400字以内，用自然段落输出，禁止任何 Markdown 符号。"""
